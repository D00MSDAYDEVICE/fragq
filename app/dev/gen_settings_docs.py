"""
Writes docs/reference/channel-settings.md and queue-settings.md from the bot's own variable
definitions, so the reference always matches the code. Start dev/demo.py first, then:

	python dev/gen_settings_docs.py [http://127.0.0.1:8000]
"""
import http.cookiejar
import json
import os
import sys
import urllib.request

BASE = (sys.argv[1] if len(sys.argv) > 1 else "http://127.0.0.1:8000").rstrip("/")
DOCS = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "docs", "reference")

TYPES = {
	"str": "text", "text": "multi-line text", "option": "choice", "bool": "on / off", "int": "number",
	"slider": "percent", "role": "role", "member": "member", "channel": "channel", "duration": "duration",
	"emoji": "emoji", "table": "table",
}

PAGES = {
	"channel": dict(
		file="channel-settings.md",
		title="Channel settings",
		intro="""Channel settings apply to one Discord channel and every queue on it. Change them in the web panel
(select the channel, then **Settings**), with `/channel set <variable> <value>`, or all at once with
`!set_channel_cfg <json>`. Members need the channel's **Admin role** (or *Edit channel settings* in the
web panel) to change them.""",
	),
	"queue": dict(
		file="queue-settings.md",
		title="Queue settings",
		intro="""Queue settings apply to a single queue. Change them in the web panel (select the queue in the
channel tree), with `/queue set <queue> <variable> <value>`, or all at once with
`!set_queue_cfg <queue> <json>`. Create a queue with **Create queue** in the web panel or
`/queue create_pickup <name> <size>`.""",
	),
}


def fetch():
	op = urllib.request.build_opener(urllib.request.HTTPCookieProcessor(http.cookiejar.CookieJar()))
	op.open(BASE + "/dev-login")
	req = urllib.request.Request(BASE + "/api/schema", headers={"X-FragQ": "1"})
	return json.load(op.open(req))


def cell(text):
	return " ".join(str(text).replace("|", "\\|").split()) if text else ""


def description(v):
	text = (v.get("description") or "").strip()
	lines = [ln.strip() for ln in text.splitlines() if ln.strip()]
	if not lines:
		return ""
	# "  draft - host a draft stage ..." style option lists become line breaks
	return "<br>".join(cell(ln) for ln in lines)


def default(v):
	d = v.get("default")
	if v["type"] == "table":
		if not d:
			return "empty"
		return f"{len(d)} rows"
	if d in (None, ""):
		return "not set"
	return f"`{cell(d)}`"


def table_details(v):
	cols = ", ".join(f"`{c['name']}`" for c in v.get("columns", []))
	out = [f"**{v['display']}** (`{v['name']}`) is a table with the columns {cols}."]
	if v.get("description"):
		out.append(description(v).replace("<br>", " "))
	if v.get("default"):
		names = [c["name"] for c in v["columns"]]
		out.append("")
		out.append("| " + " | ".join(names) + " |")
		out.append("|" + "---|" * len(names))
		for row in v["default"]:
			out.append("| " + " | ".join(cell(row.get(n)) or "–" for n in names) + " |")
	return "\n".join(out)


def page(kind, factory):
	p = PAGES[kind]
	out = [
		f"# {p['title']}",
		"",
		"<!-- Generated by app/dev/gen_settings_docs.py from the bot's variable definitions. Do not edit by hand. -->",
		"",
		p["intro"],
		"",
		"Durations are written like `1h 30m`, `45m` or `00:15:00`. Roles and channels are picked from a list in "
		"the web panel; in chat use a mention or the name.",
		"",
	]
	for section in factory["sections"]:
		rows = [v for v in factory["variables"] if v["section"] == section]
		if not rows:
			continue
		out += [f"## {section}", "", "| Setting | Variable | Type | Default | Description |", "|---|---|---|---|---|"]
		tables = []
		for v in rows:
			if v["type"] == "option" and v.get("options") and "<br>" not in description(v):
				extra = "Options: " + ", ".join(f"`{o}`" for o in v["options"]) + "."
			else:
				extra = ""
			desc = " ".join(x for x in (description(v), extra) if x)
			out.append(f"| {cell(v['display'])} | `{v['name']}` | {TYPES.get(v['type'], v['type'])} | {default(v)} | {desc} |")
			if v["type"] == "table":
				tables.append(v)
		out.append("")
		for v in tables:
			out += [table_details(v), ""]
	return "\n".join(out).rstrip() + "\n"


def main():
	schema = fetch()
	os.makedirs(DOCS, exist_ok=True)
	for kind in PAGES:
		path = os.path.join(DOCS, PAGES[kind]["file"])
		with open(path, "w", encoding="utf-8", newline="\n") as f:
			f.write(page(kind, schema[kind]))
		print("wrote", os.path.normpath(path))


if __name__ == "__main__":
	main()
